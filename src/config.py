# config.py
"""Centralized configuration management for Desktop assistant."""

import os
import platform

from dotenv import load_dotenv

load_dotenv()

# Base directory for resolving relative paths
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _env_flag(name: str, default: bool) -> bool:
    """Read a boolean environment variable without accepting ambiguous values."""
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


class Config:
    """Configuration settings for the Desktop assistant."""

    # API Keys
    GOOGLE_API_KEY = os.environ.get("GOOGLE_API_KEY")
    GROQ_API_KEY = os.environ.get("GROQ_API_KEY")
    TOGETHER_API_KEY = os.environ.get("TOGETHER_API_KEY")
    PORCUPINE_ACCESS_KEY = os.environ.get("PORCUPINE_ACCESS_KEY")
    TAVILY_API_KEY = os.environ.get("TAVILY_API_KEY")

    # LLM Configuration
    # Current Groq multimodal model: supports chat, image input, and local
    # function calling used by the LangGraph agent and screenshot workflow.
    LLM_MODEL = os.environ.get("LLM_MODEL", "qwen/qwen3.8-27b")
    LLM_PROVIDER = os.environ.get("LLM_PROVIDER", "groq")
    LLM_TEMPERATURE = float(os.environ.get("LLM_TEMPERATURE", "0.8"))
    LLM_API_KEY = {
        "google": GOOGLE_API_KEY,
        "groq": GROQ_API_KEY,
        "together": TOGETHER_API_KEY,
        "porcupine": PORCUPINE_ACCESS_KEY,
        "tavily": TAVILY_API_KEY,
    }.get(LLM_PROVIDER)

    # Logging
    LOG_LEVEL = os.environ.get("LOG_LEVEL", "INFO")

    # Audio Configuration
    PLATFORM = platform.system()
    # The repository includes only a Linux Porcupine keyword model.  Keep wake
    # word operation enabled on Linux, but make text input the safe default on
    # platforms for which no compatible model is bundled.
    WAKE_WORD_ENABLED = _env_flag("WAKE_WORD_ENABLED", PLATFORM == "Linux")
    SAMPLE_RATE = 16000
    CHANNELS = 1
    CHUNK_SIZE = SAMPLE_RATE // 10
    NUM_SAMPLES = 512
    MIN_RECORDING_SECONDS = float(os.environ.get("MIN_RECORDING_SECONDS", "0.25"))
    # Reject all-zero or near-silent captures before spending an API request.
    SILENCE_RMS_THRESHOLD = float(os.environ.get("SILENCE_RMS_THRESHOLD", "0.003"))

    # Voice Activity Detection
    CONFIDENCE_THRESHOLD = 0.5
    MAX_SILENCE_FRAMES = 60  # ~2 seconds of silence
    MAX_RECORDING_FRAMES = 20 * SAMPLE_RATE // NUM_SAMPLES  # 20 seconds max
    SPEAKER_SIMILARITY_THRESHOLD = 0.6

    # TTS Configuration
    TTS_VOICE = "en-US-RogerNeural"
    TTS_RATE = "+30%"
    TTS_CHUNK_SIZE = 1024

    # File Paths
    OWNER_VOICE_FILE = os.path.join(BASE_DIR, "data", "owner.wav")
    WAKE_WORD_MODEL = os.path.join(BASE_DIR, "wakewordmodels", "Jasper_en_linux_v3_0_0.ppn")
    SCREENSHOT_FILE = os.path.join(BASE_DIR, "screenshot.png")
    TEMP_AUDIO_FILE = os.path.join(BASE_DIR, "temp.wav")
    CHECKPOINTS_DB = os.path.join(BASE_DIR, "checkpoints", "sqlite.db")

    # Sound Effects
    START_SOUND_FILE = os.path.join(BASE_DIR, "data", "soundeffects", "start_recording.mp3")
    STOP_SOUND_FILE = os.path.join(BASE_DIR, "data", "soundeffects", "stop_recording.mp3")

    # UI Configuration
    OVERLAY_WIDTH = 400
    OVERLAY_HEIGHT = 200
    OVERLAY_X = 50
    OVERLAY_Y = 50
    MESSAGE_TIMEOUT = 5

    # Thread Configuration
    MAX_WORKERS = 3
    AUDIO_PROCESSING_TIMEOUT = 10

    # Agent Configuration
    # A named configurable thread avoids reusing the repository's old numeric
    # checkpoint, whose stale messages can affect responses after model swaps.
    THREAD_ID = os.environ.get("JASPER_THREAD_ID", "jasper")
    MAX_TOKENS_HISTORY = 10000

    # Personalization — customize the assistant's identity
    ASSISTANT_NAME = os.environ.get("ASSISTANT_NAME", "Jasper")

    # Whisper Configuration
    # Groq retired distil-whisper-large-v3-en; Turbo is the supported low-
    # latency successor and accepts 16 kHz mono WAV generated by Jasper.
    TRANSCRIPTION_MODEL = os.environ.get("TRANSCRIPTION_MODEL", "whisper-large-v3-turbo")
    TRANSCRIPTION_LANGUAGE = os.environ.get("TRANSCRIPTION_LANGUAGE", "en")
    TRANSCRIPTION_TIMEOUT = float(os.environ.get("TRANSCRIPTION_TIMEOUT", "30"))
    TRANSCRIPTION_PROMPT = (
        "Please transcribe the following audio accurately, maintaining proper "
        "punctuation and formatting. This is a conversation between a user and "
        f'a Desktop Assistant named "{ASSISTANT_NAME}". '
        f"So, focus on words like '{ASSISTANT_NAME}'."
    )

    # ADB Configuration
    ADB_HOST = os.environ.get("ADB_HOST", "127.0.0.1")
    ADB_PORT = int(os.environ.get("ADB_PORT", "5037"))

    # Mobile Device Configuration
    MOBILE_HOST = os.environ.get("MOBILE_HOST")
    MOBILE_PORT = int(os.environ.get("MOBILE_PORT", "5555"))

    OWNER_NAME = os.environ.get("OWNER_NAME", "User")
    OWNER_AGE = os.environ.get("OWNER_AGE", "")
    OWNER_LOCATION = os.environ.get("OWNER_LOCATION", "")
    OWNER_OCCUPATION = os.environ.get("OWNER_OCCUPATION", "")
    OWNER_COLLEGE = os.environ.get("OWNER_COLLEGE", "")
    OWNER_INTERESTS = os.environ.get("OWNER_INTERESTS", "")


# Create a global config instance
config = Config()
